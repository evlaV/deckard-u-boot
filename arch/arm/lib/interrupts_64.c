static void show_efi_loaded_images(struct pt_regs *regs)
{
	efi_print_image_infos((void *)regs->elr);
}

static void dump_far(unsigned long esr)
{
	unsigned long el, far;

	switch ((esr >> 26) & 0b111111) {
	case 0x20:
	case 0x21:
	case 0x24:
	case 0x25:
	case 0x22:
	case 0x34:
	case 0x35:
		break;
	default:
		return;
	}

	asm("mrs	%0, CurrentEl": "=r" (el));

	switch (el >> 2) {
	case 1:
		asm("mrs	%0, FAR_EL1": "=r" (far));
		break;
	case 2:
		asm("mrs	%0, FAR_EL2": "=r" (far));
		break;
	default:
		/* don't print anything to make output pretty */
		return;
	}

	printf(", far 0x%lx", far);
}

static void dump_instr(struct pt_regs *regs)
{
	u32 *addr = (u32 *)(regs->elr & ~3UL);
	int i;

	printf("Code: ");
	for (i = -4; i < 1; i++)
		printf(i == 0 ? "(%08x) " : "%08x ", addr[i]);
	printf("\n");
}

void show_regs(struct pt_regs *regs)
{
	int i;

	if (gd->flags & GD_FLG_RELOC)
		printf("elr: %016lx lr : %016lx (reloc)\n",
		       regs->elr - gd->reloc_off,
		       regs->regs[30] - gd->reloc_off);
	printf("elr: %016lx lr : %016lx\n", regs->elr, regs->regs[30]);

	for (i = 0; i < 29; i += 2)
		printf("x%-2d: %016lx x%-2d: %016lx\n",
		       i, regs->regs[i], i+1, regs->regs[i+1]);
	printf("\n");
	dump_instr(regs);
}

/* Stack frames automatically generated by compiler emitted code */
struct stack_frame {
	struct stack_frame *prev;
	unsigned long lr;
	char data[];
};

static void print_sym(unsigned long lr)
{
	/* Print the symbol address and the offset to the LR */
	printf("\t<%#016lx> %pS\n", lr - (gd->flags & GD_FLG_RELOC ? gd->reloc_off : 0),
	       (void *)lr);
}

/**
 * show_backtrace - show backtrace using frame pointers
 * @elr: exception link register when called from an exception context
 * @lr: link register (x30) of the current function
 * @x29: frame pointer (x29) of the current function
 */
static void show_backtrace(unsigned long elr, unsigned long lr, unsigned long x29)
{
	struct stack_frame *fp = (struct stack_frame *)x29;

	/* If we're pre-relocation then _start and text base might be the same */
	if (CONFIG_TEXT_BASE && CONFIG_TEXT_BASE != (unsigned long)_start)
		printf("\nCONFIG_TEXT_BASE   : %#lx\n", (unsigned long)CONFIG_TEXT_BASE);
	printf("Relocated base addr: %#lx\n", (unsigned long)_start);
	printf("Backtrace:\n");

	/* ELR tells us where the exception occurred */
	if (elr) {
		printf("elr:");
		print_sym(elr);
	}

	/*
	 * LR tells us the calling function, for exceptions this is the function that called
	 * the function where the exception occurred. For unwind_stack() case this is the caller
	 * of unwind_stack().
	 */
	printf("lr:");
	print_sym(lr);

	/* Now we get the rest of the backtrace from the frame pointers */
	while (fp) {
		print_sym(fp->lr);
		fp = fp->prev;
	}
	printf("\n");
}

/**
 * unwind_stack() - Unwind the callstack and print a backtrace.
 *
 * This function can be called for debugging purposes to walk backwards through
 * stack frames, printing the function name and offset of the branch instruction.
 *
 * It reads out the link register (x30) which contains the return address of the
 * caller, and x29 which contains the frame pointer of the caller.
 */
void unwind_stack(void)
{
	unsigned long x29, x30;

	asm("mov %0, x29" : "=r" (x29));
	asm("mov %0, x30" : "=r" (x30));

	show_backtrace(0, x30, x29);
}

/*
 * Try to "emulate" a semihosting call in the event that we don't have a
 * debugger attached.
 */
static bool smh_emulate_trap(struct pt_regs *regs)
{
	int size;

	if (ESR_ELx_EC(regs->esr) != ESR_ELx_EC_UNKNOWN)
		return false;

	if (regs->spsr & PSR_MODE32_BIT) {
		if (regs->spsr & PSR_AA32_T_BIT) {
			u16 *insn = (u16 *)ALIGN_DOWN(regs->elr, 2);

			if (*insn != SMH_T32_SVC && *insn != SMH_T32_HLT)
				return false;
			size = 2;
		} else {
			u32 *insn = (u32 *)ALIGN_DOWN(regs->elr, 4);

			if (*insn != SMH_A32_SVC && *insn != SMH_A32_HLT)
				return false;
			size = 4;
		}
	} else {
		u32 *insn = (u32 *)ALIGN_DOWN(regs->elr, 4);

		if (*insn != SMH_A64_HLT)
			return false;
		size = 4;
	}

	/* Avoid future semihosting calls */
	disable_semihosting();

	/* Just pretend the call failed */
	regs->regs[0] = -1;
	regs->elr += size;
	return true;
}

/**
 * except_msg() - print exception message
 *
 * Print exception message, register contents, backtrace, loaded EFI images.
 *
 * @msg:	message describing exception type
 * @pt_regs:	registers
 */
static void except_msg(const char *msg, struct pt_regs *pt_regs)
{
	efi_restore_gd();
	printf("%s handler, esr 0x%016lx\n", msg, pt_regs->esr);
	show_regs(pt_regs);
	if (CONFIG_IS_ENABLED(FRAMEPOINTER))
		show_backtrace(pt_regs->elr, pt_regs->regs[30], pt_regs->regs[29]);
	show_efi_loaded_images(pt_regs);
	panic("Resetting CPU ...\n");
}

/*
 * do_bad_sync handles the impossible case in the Synchronous Abort vector.
 */
void do_bad_sync(struct pt_regs *pt_regs)
{
	except_msg("Bad mode in \"Synchronous Abort\"", pt_regs);
}

